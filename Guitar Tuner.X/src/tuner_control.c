static ComplexNumber multiplyComplex(ComplexNumber num1, ComplexNumber num2) {
    ComplexNumber result;

    int32_t real_temp = ((int32_t) num1.real * num2.real) - ((int32_t) num1.imag * num2.imag);
    int32_t imag_temp = ((int32_t) num1.real * num2.imag) + ((int32_t) num1.imag * num2.real);

    result.real = (int16_t) (real_temp >> 15);
    result.imag = (int16_t) (imag_temp >> 15);

    return result;
}

inline uint8_t reverseBits(uint8_t number) {
    return BIT_REVERSE_TABLE[number];
}

static ComplexNumber* reorderSample(ComplexNumber sampleSet[]) {
    static ComplexNumber tempSet[SAMPLE_SIZE];
    for (int i = 0; i < SAMPLE_SIZE; i++) {
        tempSet[i] = sampleSet[reverseBits(i)];
    }
    return tempSet;
}

void FFT(ComplexNumber* data) {
    uint16_t i, j;
    uint8_t stage;

    for (i = 0; i < SAMPLE_SIZE; i++) {
        uint8_t rev = BIT_REVERSE_TABLE[i];
        if (i < rev) {
            ComplexNumber temp = data[i];
            data[i] = data[rev];
            data[rev] = temp;
        }
    }

    for (stage = 1; stage <= 8; stage++) {
        uint16_t step = 1 << stage;
        uint16_t half_step = step >> 1;

        uint16_t twiddle_step = 128 / half_step;

        for (i = 0; i < SAMPLE_SIZE; i += step) {
            for (j = 0; j < half_step; j++) {

                uint16_t twiddle_idx = j * twiddle_step;

                ComplexNumber W = TWIDDLE_TABLE[twiddle_idx];
                ComplexNumber t = multiplyComplex(W, data[i + j + half_step]);
                ComplexNumber u = data[i + j];

                data[i + j].real = (u.real + t.real) >> 1;
                data[i + j].imag = (u.imag + t.imag) >> 1;

                data[i + j + half_step].real = (u.real - t.real) >> 1;
                data[i + j + half_step].imag = (u.imag - t.imag) >> 1;
            }
        }
    }
}

uint16_t FindPeakBin(ComplexNumber *data) {
    uint16_t peak_bin = 1;
    uint32_t largest_magnitude = 0;

    for (uint16_t k = 1; k < SAMPLE_SIZE / 2; k++) {
        int32_t real = data[k].real;
        int32_t imag = data[k].imag;

        uint32_t magnitude =
                (uint32_t) (real * real) +
                (uint32_t) (imag * imag);

        if (magnitude > largest_magnitude) {
            largest_magnitude = magnitude;
            peak_bin = k;
        }
    }

    return peak_bin;
}