inline uint8_t reverseBits(uint8_t number){
    return BIT_REVERSE_TABLE[number];
}

static uint16_t* reorderSample(uint16_t sampleSet[]){
    static uint16_t tempSet[SAMPLE_SIZE];
    for (int i = 0; i < SAMPLE_SIZE; i++) {
        tempSet[i] = sampleSet[reverseBits(i)];
    }
    return tempSet;   
}

static uint16_t* revaluateSample(uint16_t sampleSet[]){
    static uint16_t tempSet[SAMPLE_SIZE];
    for (int i = 0; i < SAMPLE_SIZE; i += 2) {
        tempSet[i] = (uint16_t)(sampleSet[i] + sampleSet[i+1]);
        tempSet[i+1] = (uint16_t)(sampleSet[i] - sampleSet[i+1]);
    }
    return tempSet;   
}
